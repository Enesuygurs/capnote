// The extension of a file name, lower case with its dot. A name that is only an extension (.env,
// .gitignore) is its own extension, as Windows reads it (path.extname gives nothing for it).
export function extensionOf(filePath) {
  const name = String(filePath).split(/[\\/]/).pop().toLowerCase();
  const dot = name.lastIndexOf('.');
  return dot < 0 ? '' : name.slice(dot);
}

export const isSupportedFile = (filePath) => EXTENSIONS.includes(extensionOf(filePath));
